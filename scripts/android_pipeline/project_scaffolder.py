class AndroidProjectScaffolder:
    """Generates a complete, compilable Android Gradle project skeleton."""

    def __init__(self):
        self.created_files = []

    def scaffold(
        self,
        project_path,
        package_name="com.example.myapp",
        app_name="My App",
        ui_mode="compose",
        min_sdk=24,
        target_sdk=34,
    ):
        """Create the full project tree. Returns (success: bool, report: dict)."""
        project_path = Path(project_path).resolve()

        # --- Validations ---
        if not package_name or not isinstance(package_name, str):
            return False, {"error": "INVALID_PACKAGE", "message": "package_name must be a non-empty string"}
        parts = package_name.split(".")
        if len(parts) < 2 or not all(p.isidentifier() and not p[0].isdigit() for p in parts):
            return False, {"error": "INVALID_PACKAGE", "message": "package_name must look like com.example.app"}
        if ui_mode not in ("compose", "xml"):
            return False, {"error": "INVALID_UI_MODE", "message": "ui_mode must be 'compose' or 'xml'"}
        if not (19 <= min_sdk <= 35) or not (min_sdk <= target_sdk <= 35):
            return False, {"error": "INVALID_SDK", "message": "min_sdk/target_sdk out of supported range (19-35)"}

        app_class = "".join(w.capitalize() for w in app_name.split())
        project_name = "".join(w.capitalize() for w in app_name.split()) or "MyApp"

        if project_path.exists() and any(project_path.iterdir()):
            return False, {"error": "DIR_NOT_EMPTY", "message": f"{project_path} is not empty"}

        # --- Directory tree ---
        pkg_dir = project_path / "app" / "src" / "main" / "java" / Path(*parts)
        res_values = project_path / "app" / "src" / "main" / "res" / "values"
        res_layout = project_path / "app" / "src" / "main" / "res" / "layout"
        res_mipmap = project_path / "app" / "src" / "main" / "res" / "mipmap-anydpi-v26"
        gradle_wrapper = project_path / "gradle" / "wrapper"
        for d in (pkg_dir, res_values, res_layout, res_mipmap, gradle_wrapper):
            d.mkdir(parents=True, exist_ok=True)

        # --- Files ---
        self._write(project_path / "settings.gradle.kts", SETTINGS_GRADLE.format(project_name=project_name))
        self._write(project_path / "build.gradle.kts", ROOT_BUILD_GRADLE)
        build_template = APP_BUILD_GRADLE_COMPOSE if ui_mode == "compose" else APP_BUILD_GRADLE_XML
        self._write(
            project_path / "app" / "build.gradle.kts",
            build_template.format(package_name=package_name, min_sdk=min_sdk, target_sdk=target_sdk),
        )
        self._write(project_path / "app" / "src" / "main" / "AndroidManifest.xml", MANIFEST.format(app_class=app_class))
        self._write(
            pkg_dir / "MainActivity.kt",
            (MAIN_ACTIVITY_COMPOSE if ui_mode == "compose" else MAIN_ACTIVITY_XML).format(
                package_name=package_name, app_name=app_name
            ),
        )
        self._write(res_values / "strings.xml", STRINGS_XML.format(app_name=app_name))
        self._write(res_values / "themes.xml", THEMES_XML.format(app_class=app_class))
        self._write(project_path / "app" / "proguard-rules.pro", PROGUARD_RULES)
        self._write(project_path / "gradle.properties", GRADLE_PROPERTIES)
        self._write(project_path / ".gitignore", GITIGNORE)
        self._write(gradle_wrapper / "gradle-wrapper.properties", GRADLEW_PROPERTIES)

        if ui_mode == "xml":
            self._write(res_layout / "activity_main.xml", LAYOUT_XML)

        # Adaptive launcher icon (vector, no binary assets needed)
        self._write(res_mipmap / "ic_launcher.xml", self._adaptive_icon())
        self._write(res_values / "ic_launcher_background.xml", self._icon_background())

        # --- Local properties (Android SDK path) ---
        sdk_root = os.environ.get("ANDROID_SDK_ROOT", os.environ.get("ANDROID_HOME", ""))
        if sdk_root:
            self._write(project_path / "local.properties", f"sdk.dir={sdk_root}\n")

        # --- Gradle wrapper bootstrap ---
        wrapper_ok = self._bootstrap_gradle_wrapper(project_path)

        return True, {
            "project_path": str(project_path),
            "package_name": package_name,
            "app_name": app_name,
            "ui_mode": ui_mode,
            "min_sdk": min_sdk,
            "target_sdk": target_sdk,
            "files_created": len(self.created_files),
            "gradle_wrapper_bootstrapped": wrapper_ok,
            "next_steps": [
                "git init && git add -A && git commit -m 'feat: scaffold Android app'",
                "Copy templates/.github/workflows/android-app-factory.yml to .github/workflows/",
                "Push to GitHub and let the App Factory workflow build the APK",
            ],
        }

    def _write(self, path, content):
        path.write_text(content, encoding="utf-8")
        self.created_files.append(str(path))

    @staticmethod
    def _adaptive_icon():
        return """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@color/ic_launcher_background" />
</adaptive-icon>
"""

    @staticmethod
    def _icon_background():
        return """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#1A73E8</color>
</resources>
"""

    def _bootstrap_gradle_wrapper(self, project_path):
        """Try to generate a real Gradle wrapper if gradle is available; otherwise
        CI's setup-gradle action handles it (workflow validates this)."""
        if shutil.which("gradle"):
            try:
                res = subprocess.run(
                    ["gradle", "wrapper", "--gradle-version", "8.7"],
                    cwd=str(project_path),
                    capture_output=True,
                    text=True,
                    timeout=300,
                )
                return res.returncode == 0
            except (subprocess.TimeoutExpired, OSError):
                return False
        # No local gradle: copy wrapper scripts from this toolkit if present
        toolkit_gradlew = Path(__file__).resolve().parents[2] / "gradlew"
        if toolkit_gradlew.exists():
            shutil.copy2(toolkit_gradlew, project_path / "gradlew")
            os.chmod(project_path / "gradlew", 0o755)
            return True
        return False


def main():
    parser = argparse.ArgumentParser(description="App Factory — Android Project Scaffolder")
    parser.add_argument("project_path", help="Target directory for the new project")
    parser.add_argument("--package", default="com.example.myapp", help="Application package name")
    parser.add_argument("--name", default="My App", help="Human-readable app name")
    parser.add_argument("--ui", choices=["compose", "xml"], default="compose", help="UI toolkit")
    parser.add_argument("--min-sdk", type=int, default=24)
    parser.add_argument("--target-sdk", type=int, default=34)
    args = parser.parse_args()

    scaffolder = AndroidProjectScaffolder()
    ok, report = scaffolder.scaffold(args.project_path, args.package, args.name, args.ui, args.min_sdk, args.target_sdk)
    print(json.dumps(report, indent=2))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
